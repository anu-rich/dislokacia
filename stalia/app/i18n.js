  /** Languages shipped in lang/, in the order they appear in the language menu. */
  const LANGUAGE_FILES = ['zh', 'ru', 'kk', 'uk', 'tr', 'el'];

  const STRINGS = {}, LANG_LABELS = {}, LANG_NAMES = {}, FORMATS = {}, EXAMPLES = {};
  const LANGS = [];

  /**
   * Register a language pack: { code, label, name, format, examples, strings }.
   * format: locale (for number formatting), date and dayShort patterns built from DD, MM, MMM, YYYY,
   *         durSpace (space between a number and its unit), csvSep (list separator in spreadsheets).
   */
  function add(pack) {
    if (!pack || !pack.code || !pack.strings) return;
    if (LANGS.indexOf(pack.code) < 0) {
      // the menu order is the one above, whatever order the files were loaded in
      const rank = (c) => { const i = c === 'en' ? 0 : LANGUAGE_FILES.indexOf(c) + 1; return i > 0 || c === 'en' ? i : 999; };
      LANGS.push(pack.code);
      LANGS.sort((x, y) => rank(x) - rank(y));
    }
    STRINGS[pack.code] = pack.strings;
    LANG_LABELS[pack.code] = pack.label || pack.code.toUpperCase();
    LANG_NAMES[pack.code] = pack.name || pack.code;
    FORMATS[pack.code] = Object.assign({}, FORMATS.en, pack.format || {});
    EXAMPLES[pack.code] = Object.assign({}, EXAMPLES.en, pack.examples || {});
  }
  add({
    code: 'en', label: 'EN', name: 'English',
    format: { locale: 'en-US', date: 'DD MMM YYYY', dayShort: 'DD MMM', durSpace: false, csvSep: ',' },
    examples: enExamples, strings: en,
  });

  /** Translate `key` into `lang`, filling {placeholders} from `vars`. Unknown keys return the key. */
  function t(lang, key, vars) {
    const dict = STRINGS[lang] || en;
    let s = dict[key];
    if (s == null) s = en[key];
    if (s == null) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
    return s;
  }

  const format = (lang) => FORMATS[lang] || FORMATS.en;
  const examplesText = (lang) => EXAMPLES[lang] || EXAMPLES.en;

  /** Best available language for this browser. */
  function detect() {
    let l = 'en';
    try { l = String((navigator.languages && navigator.languages[0]) || navigator.language || 'en').toLowerCase(); } catch (e) { /* no navigator */ }
    const two = l.slice(0, 2);
    if (STRINGS[two]) return two;
    // Russian is the working language of shipping offices in these countries
    if (/^(be|ky|uz|tg)$/.test(two) && STRINGS.ru) return 'ru';
    return 'en';
  }

  return { STRINGS, LANGS, LANG_LABELS, LANG_NAMES, LANGUAGE_FILES, add, t, format, examplesText, detect };
